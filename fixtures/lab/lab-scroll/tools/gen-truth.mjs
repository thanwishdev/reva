// Generates truth/<id>.json for review (run: node tools/gen-truth.mjs). Default parameters, planned frames, regimes R2 and R3
// for the first trace of the route, plus the closed-form values for every grid point. Never served to a page.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { truth } from '../truth.mjs';
import { routesFile } from '../plan.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function buildTruthFiles() {
  const out = {};
  for (const r of routesFile().routes) {
    const variant = Object.keys(r.traces)[0];
    const doc = {
      schema: 'reva.labtruth-review/0', route: r.id, note: 'generated by tools/gen-truth.mjs; regime-dependent values come from the planned trace',
      default: { R2: truth(r.id, r.params.default, 'R2', variant), R3: truth(r.id, r.params.default, 'R3', variant) },
      grid: r.params.grid.map(p => { const t = truth(r.id, p, 'R3', variant); return { params: t.params, items: t.items.filter(i => i.scored).map(i => ({ target: i.target, class: i.class, law: i.law, params: i.params, derived: i.derived && Object.fromEntries(Object.entries(i.derived).filter(([k]) => !/tails|crossings|runs/.test(k))) })) }; }),
    };
    out[`${r.id}.json`] = JSON.stringify(doc, null, 1) + '\n';
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(path.join(root, 'truth'), { recursive: true });
  for (const [name, text] of Object.entries(buildTruthFiles())) fs.writeFileSync(path.join(root, 'truth', name), text);
}
